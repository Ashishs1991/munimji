create table reminder_tasks (
    id uuid primary key,
    business_id uuid not null references businesses (id),
    actor_id uuid not null,
    kind text not null,
    status text not null,
    party_id uuid references parties (id),
    document_id uuid references documents (id),
    contact text,
    note_only boolean not null,
    approved_amount_paise bigint,
    approved_payload text,
    schedule_version integer not null,
    scheduled_at timestamptz,
    local_date date,
    local_time time,
    timezone text not null,
    consent boolean not null,
    template_name text,
    send_key text unique,
    provider_status text,
    provider_id text,
    outcome text,
    constraint reminder_tasks_kind check (kind in ('OWNER_REMINDER', 'CUSTOMER_SEND')),
    constraint reminder_tasks_status check (status in (
        'AWAITING_APPROVAL',
        'SCHEDULED',
        'SENDING',
        'PROVIDER_ACCEPTED',
        'DELIVERED',
        'CANCELED',
        'SUPPRESSED_PAID',
        'BLOCKED',
        'FAILED',
        'NEEDS_REAPPROVAL',
        'OUTCOME_UNKNOWN',
        'MISSED',
        'DASHBOARD'
    ))
);
